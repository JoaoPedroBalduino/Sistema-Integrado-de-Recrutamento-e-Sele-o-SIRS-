test('explica o acesso no canto sem tirar o foco da página', async ({ page }) => {
  await entrar(page)
  await page.goto('/conta')
  const abrir = page.getByRole('button', { name: 'Entenda seu acesso', exact: true })
  await abrir.click()
  const mensagem = page.getByRole('status', { name: 'Sobre o seu acesso', exact: true })
  await expect(mensagem).toContainText('Seu perfil define as páginas e ações disponíveis')
  await page.screenshot({
    path: test.info().outputPath('aviso-canto-informacao.png'),
    fullPage: true,
  })
  await expect(abrir).toBeFocused()
  await mensagem.getByRole('button', { name: 'Fechar mensagem' }).click()
  await abrir.click()
  await mensagem.getByRole('button', { name: 'Fechar mensagem' }).click()
  await expect(mensagem).toHaveCount(0)
})

test('preserva o formulário após erro e confirma o sucesso ao salvar', async ({ page }) => {
  await entrar(page)
  await page.goto('/cadastros')
  await page.getByRole('button', { name: 'Novo registro', exact: true }).click()
  await page.getByLabel('Nome', { exact: true }).fill('Duplicado')
  await page.getByRole('button', { name: 'Salvar alterações', exact: true }).click()
  const erro = page.getByRole('alert', { name: 'Não foi possível concluir', exact: true })
  await expect(erro).toContainText('Nome já cadastrado')
  await erro.getByRole('button', { name: 'Fechar mensagem', exact: true }).click()
  await expect(page.getByLabel('Nome', { exact: true })).toHaveValue('Duplicado')
  await page.getByLabel('Nome', { exact: true }).fill('Equipe de Verificação')
  await page.getByRole('button', { name: 'Salvar alterações', exact: true }).click()
  const sucesso = page.getByRole('status', { name: 'Operação concluída', exact: true })
  await expect(sucesso).toContainText('Informações salvas com sucesso.')
  await page.screenshot({ path: test.info().outputPath('aviso-canto-sucesso.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await sucesso.getByRole('button', { name: 'Fechar mensagem', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Equipe de Verificação', exact: true })).toBeVisible()
})

test('confirmação no canto não bloqueia a tela e desaparece sem interação', async ({ page }) => {
  await page.clock.install()
  await page.goto('/login')
  await page.getByLabel('E-mail corporativo').fill('coordenacao@exemplo.test')
  await page.getByLabel('Senha', { exact: true }).fill('SenhaTesteFrontend123!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  const mensagem = page.getByRole('status', { name: 'Login realizado', exact: true })
  await expect(mensagem).toBeVisible()
  await expect(page.locator('dialog[open]')).toHaveCount(0)
  await expect.poll(async () => (await mensagem.boundingBox())?.y ?? 9999).toBeLessThan(40)
  const limites = await mensagem.boundingBox()
  expect(limites!.x + limites!.width).toBeGreaterThan(page.viewportSize()!.width - 40)
  await page.mouse.move(0, 500)
  await page.clock.runFor(8100)
  await expect(mensagem).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Sair da conta' })).toBeEnabled()
})
