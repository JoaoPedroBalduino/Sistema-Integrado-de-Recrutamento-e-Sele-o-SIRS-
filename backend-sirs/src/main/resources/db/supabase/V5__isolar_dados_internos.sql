-- Schema privado: acesso via JDBC e autorizacao do backend, nao pela Data API.
REVOKE ALL ON SCHEMA sirs FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA sirs FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA sirs FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA sirs REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA sirs REVOKE ALL ON SEQUENCES FROM PUBLIC;
DO $$
DECLARE papel TEXT;
BEGIN
    FOR papel IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon','authenticated','service_role') LOOP
        EXECUTE format('REVOKE ALL ON SCHEMA sirs FROM %I',papel);
        EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA sirs FROM %I',papel);
        EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA sirs FROM %I',papel);
        EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA sirs REVOKE ALL ON TABLES FROM %I',papel);
        EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA sirs REVOKE ALL ON SEQUENCES FROM %I',papel);
    END LOOP;
END $$;
